#!/usr/bin/env python3
"""Create a minimal native Android project from a JSON spec; no pip dependencies."""
import argparse, json, pathlib, re

ROOT=pathlib.Path(__file__).resolve().parents[1]
def generate(spec, root=ROOT):
    slug=spec["slug"].strip().lower().replace("-", "_").replace(" ", "_")
    if not re.fullmatch(r"[a-z][a-z0-9_]{2,29}",slug):
        raise ValueError("slug must be 3-30 lowercase letters, digits or underscores")
    label=spec.get("title",slug)
    if not isinstance(label,str) or not 1<=len(label)<=60:
        raise ValueError("Invalid title")
    package="com.akudama."+slug.replace("_","")
    target=root/"projects"/slug
    if target.exists(): raise FileExistsError(str(target))
    src=target/"app"/"src"/"main"
    java=src/"java"/pathlib.Path(*package.split("."))
    java.mkdir(parents=True)
    (target/"settings.gradle").write_text("pluginManagement { repositories { google(); mavenCentral(); gradlePluginPortal() } }\ndependencyResolutionManagement { repositoriesMode.set(RepositoriesMode.FAIL_ON_PROJECT_REPOS); repositories { google(); mavenCentral() } }\nrootProject.name = '"+slug+"'\ninclude ':app'\n")
    (target/"build.gradle").write_text("plugins { id 'com.android.application' version '8.7.3' apply false }\n")
    (target/"app"/"build.gradle").write_text("""plugins { id 'com.android.application' }
android {
    namespace '"""+package+"""'
    compileSdk 35
    defaultConfig {
        applicationId '"""+package+"""'
        minSdk 26
        targetSdk 35
        versionCode 1
        versionName '0.1.0'
    }
    compileOptions {
        sourceCompatibility JavaVersion.VERSION_17
        targetCompatibility JavaVersion.VERSION_17
    }
}
""")
    import html
    (src/"AndroidManifest.xml").write_text('<manifest xmlns:android="http://schemas.android.com/apk/res/android"><application android:label="'+html.escape(label,quote=True)+'" android:theme="@android:style/Theme.Material.NoActionBar"><activity android:name=".MainActivity" android:exported="true"><intent-filter><action android:name="android.intent.action.MAIN"/><category android:name="android.intent.category.LAUNCHER"/></intent-filter></activity></application></manifest>')
    escaped=json.dumps(label,ensure_ascii=False)
    (java/"MainActivity.java").write_text("""package """+package+""";
import android.app.Activity;
import android.os.Bundle;
import android.graphics.Color;
import android.view.Gravity;
import android.widget.LinearLayout;
import android.widget.TextView;
public class MainActivity extends Activity {
    @Override public void onCreate(Bundle state) {
        super.onCreate(state);
        LinearLayout root=new LinearLayout(this);
        root.setOrientation(LinearLayout.VERTICAL);
        root.setGravity(Gravity.CENTER);
        root.setPadding(32,32,32,32);
        root.setBackgroundColor(Color.rgb(11,17,29));
        TextView title=new TextView(this);
        title.setText("""+escaped+""");
        title.setTextColor(Color.WHITE);
        title.setTextSize(32);
        title.setGravity(Gravity.CENTER);
        root.addView(title);
        TextView note=new TextView(this);
        note.setText("Generated by Akudama DevTools");
        note.setTextColor(Color.rgb(139,196,255));
        note.setTextSize(16);
        note.setGravity(Gravity.CENTER);
        root.addView(note);
        setContentView(root);
    }
}
""")
    tests=root/"tests"
    tests.mkdir(exist_ok=True)
    (tests/(slug+".json")).write_text(json.dumps({"steps":[{"action":"assert_text","text":label},{"action":"assert_text","text":"Generated by Akudama DevTools"}]},ensure_ascii=False,indent=2)+"\n")
    print(f"Generated {target.relative_to(root)} with {package}")
    return target

if __name__=="__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument("--slug")
    parser.add_argument("--title")
    parser.add_argument("--spec")
    args=parser.parse_args()
    spec=json.loads(pathlib.Path(args.spec).read_text(encoding="utf-8")) if args.spec else {"slug":args.slug,"title":args.title or args.slug}
    generate(spec)
